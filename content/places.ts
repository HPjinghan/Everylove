/**
 * 外出地点（D-038；D-254 跑团式改版）：把相处从手机屏幕里拿出来的空间。每个地点是一张「场景卡」：
 * - rule：这里的规矩——duo 只能两个人（选一位坐过去）/ group 最多三个人一起聊 / quiet 不能出声（只能做动作、传纸条，
 *   出声会被工作人员过来制止，三次请出去）/ cinema 开场后只能小声说，旁白推进电影。约会永远是两个人。
 * - hours：营业时间（时，close 可以过 24 表示次日凌晨）；不写 = 全天。打烊了照样能去，看到的是 closed 那段描写、没有人。
 * - scenes：按时段的场景描写（给模型看，中文）；缺的时段用 scene。
 * - actions：输入框上方的现成动作（界面文案，t() 键；点了填成（…））。
 * - npc：旁白替哪个工作人员说话（店员 / 管理员 / 放映员……），没有就不写。
 * - capacity：同一时段这里最多几个人（duo 也可以有两位在场，她选一位）。
 * 名字 / hook / actions 是界面文案（中文原文即键，各语言在 lib/i18n.ts）；scene 类是给引擎的设定。
 * 地点的像素贴画按 id 取（content/pixel-art.ts）。纪律同桌面：做少而真——每个地点要有能玩的场景语法才上架。
 */

export type PlaceRule = 'duo' | 'group' | 'quiet' | 'cinema';
export type DayPart = 'morning' | 'day' | 'evening' | 'night';

export interface Place {
  id: string;
  name: string;
  /** 给用户看的一句钩子 */
  hook: string;
  /** 给引擎的场景设定（缺省时段）：这里长什么样、有什么可互动的东西 */
  scene: string;
  /** 按时段的场景设定；缺的用 scene */
  scenes?: Partial<Record<DayPart, string>>;
  /** 营业时间 [开, 关]（时；关可 > 24 表示次日凌晨）；不写 = 全天 */
  hours?: [number, number];
  /** 打烊时的样子（给引擎；她一个人来，没有人在） */
  closedScene?: string;
  rule: PlaceRule;
  /** 现成动作（界面文案键），点了填成（…） */
  actions: string[];
  /** 旁白替谁说话（工作人员，界面不显示；给引擎） */
  npc?: string;
  /** 同一时段最多几个人在 */
  capacity: number;
  /** 广场（D-040）：主要是陌生人；不出现在约定选项里 */
  stranger?: boolean;
}

